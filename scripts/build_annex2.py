"""Generate Annex 2.1 (price tiers) and Annex 2.2 (covered jurisdictions) of the
Septeo reseller agreement from curation/price_bands.json.

The annex used to be hand-edited, drifted from the data, and the drift was
invisible: on 14.09.2026 the tier counts matched by coincidence while the
underlying sets differed. Nothing in section 2.1 or 2.2 may be typed by hand
again -- edit the JSON, re-run this, and let --check fail the build if someone
does it anyway.

    python scripts/build_annex2.py --check     # exit 1 if the document drifted
    python scripts/build_annex2.py --write     # regenerate the two sections
    python scripts/build_annex2.py             # print the fragments

Procurement costs are the CONTRACTED per-case fees from the supply Order Form,
not the list prices on the coverage page. They live here because they are a
commercial term of our own, not a property of the coverage data.
"""
