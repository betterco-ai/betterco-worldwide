def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--price-list", action="store_true")
    args = ap.parse_args()

    data = load()
    js = data["jurisdictions"]
    c = counts(js)
    total = len(js)

    frag_tiers = tiers_fragment(js)
    frag_juris = jurisdictions_fragment(js)

    if args.price_list:
        print("price list ->", write_price_list(js, data))
        if not (args.write or args.check):
            return 0

    if not (args.write or args.check):
        print(frag_tiers)
        print()
        print(frag_juris)
        return 0

    with io.open(DOC, encoding="utf-8") as fh:
        html = fh.read()

    if args.check:
        problems = []
        m = re.search(r"(\d+)\s+jurisdictions are covered", html)
        if not m:
            problems.append("cannot find the jurisdiction count sentence in Annex 2.2")
        elif int(m.group(1)) != total:
            problems.append("Annex 2.2 says %s jurisdictions, price_bands.json has %d"
                            % (m.group(1), total))
        # the legend chip is class="chip stp inline" and is deliberately not counted
        chips = len(re.findall(r'class="chip(?: stp)?">', html))
        if chips != total:
            problems.append("Annex 2.2 renders %d chips, price_bands.json has %d"
                            % (chips, total))
        for tier in ("A", "B", "C", "D"):
            pat = r'<td class="klass">%s</td><td class="price">(\d+)</td>' % tier
            mm = re.search(pat, html)
            if not mm:
                problems.append("tier %s row not found or reformatted" % tier)
            elif int(mm.group(1)) != c[tier]:
                problems.append("tier %s says %s jurisdictions, data has %d"
                                % (tier, mm.group(1), c[tier]))
        # amounts must NOT appear in the contract (they live in the price list)
        for tier, (cost, _) in TIER_COST.items():
            if cost + " &euro;" in html or cost + " €" in html:
                problems.append("procurement cost %s for tier %s appears in the "
                                "contract; amounts belong in the price list only"
                                % (cost, tier))
        if problems:
            print("DRIFT between price_bands.json and Annex 2:")
            for p in problems:
                print("  - " + p)
            return 1
        print("Annex 2 matches price_bands.json (%d jurisdictions, %s)"
              % (total, dict(c)))
        return 0

    html = splice(html, "2.1", frag_tiers)
    html = splice(html, "2.2", frag_juris, keep_lead=False)
    with io.open(DOC, "w", encoding="utf-8") as fh:
        fh.write(html)
    print("Annex 2 regenerated: %d jurisdictions, %s" % (total, dict(c)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
