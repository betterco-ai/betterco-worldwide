def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    data = load()
    js = data["jurisdictions"]
    c = counts(js)
    total = len(js)

    frag_tiers = tiers_fragment(js)
    frag_juris = jurisdictions_fragment(js, data)

    if not (args.write or args.check):
        print(frag_tiers)
        print()
        print(frag_juris)
        return 0

    with io.open(DOC, encoding="utf-8") as fh:
        html = fh.read()

    if args.check:
        problems = []
        m = re.search(r"(\d+)\s+jurisdictions are covered", html)
        if not m:
            problems.append("cannot find the jurisdiction count sentence in Annex 2.2")
        elif int(m.group(1)) != total:
            problems.append("Annex 2.2 says %s jurisdictions, price_bands.json has %d"
                            % (m.group(1), total))
        # Compare the SET of names, not the count. On 14.09.2026 the tier counts
        # matched by coincidence while the underlying sets differed, and a count
        # check passed on data that was wrong.
        rendered = set(re.findall(r'<span class="chip(?: stp| sub)?">([^<]+)<b>', html))
        expected = set(v["en"] for v in js.values())
        for entries in (data.get("subJurisdictions") or {}).values():
            expected |= set(e["en"] for e in entries)
        missing = sorted(expected - rendered)
        extra = sorted(rendered - expected)
        if missing:
            problems.append("Annex 2.2 is missing %d of %d jurisdictions: %s"
                            % (len(missing), len(expected), ", ".join(missing[:8])))
        if extra:
            problems.append("Annex 2.2 renders %d names not in the data: %s"
                            % (len(extra), ", ".join(extra[:8])))
        for tier in ("A", "B", "C", "D"):
            cost, _ = TIER_COST[tier]
            pat = (r'<td class="klass">%s</td><td class="price">%s &euro;</td>'
                   r'<td class="price soft">[^<]*</td><td class="price">(\d+)</td>'
                   % (tier, re.escape(cost)))
            mm = re.search(pat, html)
            if not mm:
                problems.append("tier %s row missing, reformatted, or its "
                                "procurement cost changed" % tier)
            elif int(mm.group(1)) != c[tier]:
                problems.append("tier %s says %s jurisdictions, data has %d"
                                % (tier, mm.group(1), c[tier]))

        if problems:
            print("DRIFT between price_bands.json and Annex 2:")
            for p in problems:
                print("  - " + p)
            return 1
        print("Annex 2 matches price_bands.json (%d jurisdictions, %s)"
              % (total, dict(c)))
        return 0

    html = splice(html, "2.1", frag_tiers)
    html = splice(html, "2.2", frag_juris, keep_lead=False)
    with io.open(DOC, "w", encoding="utf-8") as fh:
        fh.write(html)
    print("Annex 2 regenerated: %d jurisdictions, %s" % (total, dict(c)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
